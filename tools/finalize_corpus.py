#!/usr/bin/env python3
"""Stratify verified mutants and emit a generated baseline report.

Stratification targets ~1/3 in each of gap=0, 0<gap<=50, gap>50 (plan §6), with
a fourth "unlocalizable" class for errors TeX reports with no line at all --
these are the extreme of the phenomenon the harness exists to solve, so they are
kept as their own bucket rather than discarded.
"""
import argparse
import json
import math
import random
import statistics as st
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
META = ROOT / "corpus" / "meta"
TARGET = 1000
SEED = 20260720


def bucket(r):
    g = r.get("gap")
    if g is None or g == "inf":
        return "unlocalizable" if g is None else "other-file"
    if isinstance(g, str):
        return "other-file"
    if g == 0:
        return "gap=0"
    if g <= 50:
        return "0<gap<=50"
    return "gap>50"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=META / "baseline.generated.md",
        help="report path (default: corpus/meta/baseline.generated.md)",
    )
    args = parser.parse_args()
    output = args.output if args.output.is_absolute() else ROOT / args.output

    ver = json.load(open(META / "mutants_all_verified.json"))
    broken = [r for r in ver if r.get("status") == "broken"]
    rng = random.Random(SEED)

    by = defaultdict(list)
    for r in broken:
        by[bucket(r)].append(r)
    for v in by.values():
        rng.shuffle(v)

    # Three primary buckets get 1/3 each; unlocalizable/other-file fill the rest.
    primary = ["gap=0", "0<gap<=50", "gap>50"]
    quota = TARGET // 3
    chosen = []
    for b in primary:
        chosen += by[b][:quota]
    extra = TARGET - len(chosen)
    pool = by["unlocalizable"] + by["other-file"]
    rng.shuffle(pool)
    chosen += pool[:extra]
    if len(chosen) < TARGET:  # top up from whatever is left
        left = [r for r in broken if r not in chosen]
        rng.shuffle(left)
        chosen += left[:TARGET - len(chosen)]

    (META / "broken_corpus.json").write_text(json.dumps(chosen, indent=1))

    # ---------------- report ----------------
    lb = json.load(open(META / "local_bench.json"))
    ab = json.load(open(META / "arxiv_bench.json"))
    lc = [r for r in lb if r.get("status") == "clean"]
    ac = [r for r in ab if r.get("status") == "clean"]

    def row(name, rs, key):
        v = [r[key] for r in rs if r.get(key)]
        if not v:
            return f"| {name} | – | – | – | – |"
        return (f"| {name} | {st.median(v):.2f} | {st.mean(v):.2f} | "
                f"{min(v):.2f} | {max(v):.2f} |")

    L = []
    A = L.append
    A("# aiTeX — Baseline Timings\n")
    A("Numbers to beat. Generated by `tools/bench.py` / `tools/verify_mutants.py`.\n")
    A("**Machine:** TeX Live 2024, pdfTeX 1.40.26, 14 cores / 36 GB, macOS (Darwin 23.1.0).  ")
    A("**Flags (all runs):** `max_print_line=1000 -file-line-error "
      "-interaction=nonstopmode -no-shell-escape`, "
      "`SOURCE_DATE_EPOCH` + `FORCE_SOURCE_DATE=1` for reproducible PDFs.  ")
    A("**Method:** each project copied to scratch, build artifacts stripped; "
      "cold = first run, warm = median of runs 2–3.\n")

    A("## Corpus\n")
    A("| Set | Projects | Clean | Broken/failed | Pages (clean) |")
    A("|---|---|---|---|---|")
    A(f"| Local (published papers, `~/Dropbox/research`) | {len(lb)} | {len(lc)} | "
      f"{len(lb)-len(lc)} | {sum(r.get('pages') or 0 for r in lc)} |")
    A(f"| arXiv (all sections) | {len(ab)} | {len(ac)} | {len(ab)-len(ac)} | "
      f"{sum(r.get('pages') or 0 for r in ac)} |")
    A(f"| **Total clean** | {len(lb)+len(ab)} | **{len(lc)+len(ac)}** | | |\n")

    secs = Counter((r.get("section") or "?").split(".")[0] for r in ac)
    A("arXiv clean set spans " + ", ".join(f"`{k}` ({v})" for k, v in secs.most_common()) + ".\n")

    A("## Total compile time — clean corpus\n")
    A("Seconds. `latexmk` runs to convergence (multiple passes + bib); "
      "`pdflatex` is a single pass.\n")
    A("| Measurement | Median | Mean | Min | Max |")
    A("|---|---|---|---|---|")
    A(row("Local · pdflatex cold", lc, "pdflatex_cold_s"))
    A(row("Local · pdflatex warm", lc, "pdflatex_warm_s"))
    A(row("Local · latexmk to convergence", lc, "latexmk_s"))
    A(row("arXiv · pdflatex cold", ac, "pdflatex_cold_s"))
    A(row("arXiv · pdflatex warm", ac, "pdflatex_warm_s"))
    A(row("arXiv · latexmk to convergence", ac, "latexmk_s"))
    A("")

    allc = lc + ac
    cold = [r["pdflatex_cold_s"] for r in allc if r.get("pdflatex_cold_s")]
    warm = [r["pdflatex_warm_s"] for r in allc if r.get("pdflatex_warm_s")]
    mk = [r["latexmk_s"] for r in allc if r.get("latexmk_s")]
    A("**Headline (all clean projects):**\n")
    A(f"- single-pass `pdflatex`: **{st.median(warm):.2f}s** median "
      f"(first run {st.median(cold):.2f}s)")
    A(f"- `latexmk` to convergence: **{st.median(mk):.2f}s** median")
    A(f"- convergence costs **{st.median(mk)/st.median(warm):.1f}×** a single pass "
      f"— the prize for rerun prediction (plan §7)\n")
    delta = 100 * (1 - st.median(warm) / st.median(cold))
    A(f"> **Repeated runs save only {delta:.0f}%.** Re-running `pdflatex` on an "
      "unchanged document is nearly as expensive as the first run: it reloads the "
      "format, re-reads every package, and re-executes the whole preamble every "
      "time. There is no process-level warm path to exploit.\n>\n"
      "> This is a *supporting* result for plan §7 rather than a discouraging one. "
      "It says the ~60% preamble-snapshot win cannot come from OS or filesystem "
      "caching — pdfTeX already benefits from those here — so it has to come from "
      "architecture: snapshotting interpreter state at `\\begin{document}` and "
      "resuming, which no stock engine does.\n")

    A("## Time to first error — broken corpus\n")
    tte = [r["time_to_error_s"] for r in chosen if r.get("time_to_error_s")]
    A(f"`pdflatex -halt-on-error`, {len(tte)} mutants.\n")
    A("| Measurement | Median | Mean | Min | Max |")
    A("|---|---|---|---|---|")
    A(f"| Time to first error | {st.median(tte):.2f} | {st.mean(tte):.2f} | "
      f"{min(tte):.2f} | {max(tte):.2f} |")
    A("")

    A("## Localization gap distribution\n")
    A("`gap = |reported_line − true_line|`. The whole point of the corpus: "
      "log-only parsing degrades as gap grows.\n")
    A("| Bucket | Count | Meaning |")
    A("|---|---|---|")
    bk = Counter(bucket(r) for r in chosen)
    meaning = {
        "gap=0": "pdflatex points exactly at the cause",
        "0<gap<=50": "near miss — same file, wrong line",
        "gap>50": "**non-localized** — cause far from report",
        "unlocalizable": "**no line reported at all**",
        "other-file": "**reported in a different file**",
    }
    for k in ["gap=0", "0<gap<=50", "gap>50", "unlocalizable", "other-file"]:
        if bk.get(k):
            A(f"| `{k}` | {bk[k]} | {meaning[k]} |")
    A(f"| **total** | **{len(chosen)}** | |\n")

    nonlocal_n = bk.get("gap>50", 0) + bk.get("unlocalizable", 0) + bk.get("other-file", 0)
    A(f"**{100*nonlocal_n/len(chosen):.0f}% of the corpus is non-localized** "
      "(gap>50, no line, or wrong file) — where the harness must earn its keep.\n")

    A("## Gap by mutation family\n")
    A("| Family | n | gap=0 | 0<gap≤50 | gap>50 | unlocalizable | other-file |")
    A("|---|---|---|---|---|---|---|")
    fam = defaultdict(Counter)
    for r in chosen:
        fam[r["family"]][bucket(r)] += 1
    for f in sorted(fam, key=lambda x: -sum(fam[x].values())):
        c = fam[f]
        n = sum(c.values())
        A(f"| `{f}` | {n} | {c.get('gap=0',0)} | {c.get('0<gap<=50',0)} | "
          f"{c.get('gap>50',0)} | {c.get('unlocalizable',0)} | {c.get('other-file',0)} |")
    A("")

    stat = Counter(r["status"] for r in ver)
    A("## Mutation yield\n")
    A(f"- candidates generated: **{len(ver)}**")
    for k, v in stat.most_common():
        A(f"- `{k}`: {v}")
    A(f"\n`no-op` mutants (still compile) are discarded — this is the "
      f"*mutation validity* property from plan §9, and it fires on "
      f"{100*stat.get('no-op',0)/len(ver):.0f}% of candidates.\n")

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(L))
    print(f"[final] broken corpus: {len(chosen)}")
    for k, v in bk.most_common():
        print(f"   {v:5}  {k}")
    print(f"[final] wrote {output}")


if __name__ == "__main__":
    main()
