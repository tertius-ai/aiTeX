/// Is this a control sequence LaTeX provides?
pub fn is_kernel_macro(name: &str) -> bool {
    KERNEL_MACROS.binary_search(&name).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_list_is_sorted_for_binary_search() {
        assert!(
            KERNEL_MACROS.windows(2).all(|w| w[0] < w[1]),
            "must be sorted and deduped"
        );
    }

    #[test]
    fn contains_the_macros_documents_actually_use() {
        for n in [
            "section",
            "textbf",
            "begin",
            "frac",
            "alpha",
            "includegraphics",
            "item",
        ] {
            assert!(is_kernel_macro(n), "{n} should be known");
        }
    }

    #[test]
    fn excludes_internal_and_unknown_names() {
        assert!(!is_kernel_macro("my@internal"));
        assert!(!is_kernel_macro("definitelynotamacro"));
        assert!(!is_kernel_macro(""));
    }
}
